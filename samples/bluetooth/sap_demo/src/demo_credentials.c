const struct bt_sap_device_credential *demo_credentials_select(enum sap_role role)
{
#if defined(CONFIG_SAMPLE_BT_SAP_USE_CUSTOM_CREDENTIALS)
	ARG_UNUSED(role);
	return custom_credentials_select();
#endif

#if !defined(CONFIG_SAMPLE_BT_SAP_ROLE_PERIPHERAL)
	ARG_UNUSED(role);
	return &insecure_demo_central_credentials[0];
#else
	size_t i;

	if (role == SAP_ROLE_CENTRAL) {
		return &insecure_demo_central_credentials[0];
	}

	for (i = 0; i < ARRAY_SIZE(insecure_demo_peripheral_credentials); i++) {
		if (insecure_demo_peripheral_credentials[i].cert.body.device_id ==
		    CONFIG_SAMPLE_BT_SAP_PERIPHERAL_ID) {
			return &insecure_demo_peripheral_credentials[i];
		}
	}

	return &insecure_demo_peripheral_credentials[0];
#endif
}

const uint8_t *demo_credentials_ca_public_key(size_t *len)
{
#if defined(CONFIG_SAMPLE_BT_SAP_USE_CUSTOM_CREDENTIALS)
	if (len != NULL) {
		*len = sizeof(custom_ca_public_key);
	}

	return custom_ca_public_key;
#endif

	if (len != NULL) {
		*len = sizeof(insecure_demo_sap_ca_public_key);
	}

	return insecure_demo_sap_ca_public_key;
}
