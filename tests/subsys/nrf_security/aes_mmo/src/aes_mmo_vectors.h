/*
 * AES-MMO (Zigbee) test vectors.
 *
 * The first vector is the install code example from the Zigbee specification:
 * hashing an install code together with its CRC yields the link key, which makes
 * it the one vector in this file with an external source.
 *
 * The remaining vectors cover the padding rule of Zigbee clause B.6 around every
 * boundary that matters: an empty message, a message that leaves no room for the
 * length field (13, 14, 15 bytes), exact block multiples, and the longest message
 * the 16-bit length field can express (8191 bytes). Their messages are generated
 * by aes_mmo_fill_pattern() instead of being stored, and their digests come from an
 * independent Python implementation that reproduces the install code vector above.
 */

