/* The message pattern that the digests above were computed over. */
static inline void aes_mmo_fill_pattern(uint8_t *buffer, size_t len)
{
	for (size_t i = 0; i < len; i++) {
		buffer[i] = (uint8_t)(i * 7 + 3);
	}
}

